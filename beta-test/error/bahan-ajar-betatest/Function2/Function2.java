package Function2;
public class Function2 {

  public static int pangkatTiga(int n) {
    return (n * n * n);
  }

  public static void main(String[] args) {
    int angka = 2;
    System.out.println(pangkatTiga(angka));}
}

// Output yang diharapkan adalah hasil pangkat Tiga dari variabel angka
// 8
